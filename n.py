# Write a function that takes two numbers and returns their sum.
# Call it with example values and print the result.

# 💡 TIP:
# Use `def`, `return`, and call it like `f(2, 3)`.
def add_numbers(a, b):
    return a + b

result = add_numbers(2, 3)
print(f"The sum of 2 and 3 is: {result}")

print(f"The sum of 10 and 5 is: {add_numbers(10, 5)}")
print(f"The sum of 7.5 and 2.3 is: {add_numbers(7.5, 2.3)}")