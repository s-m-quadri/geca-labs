# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
a=int(input("enter number 1:"))
b=int(input("enter number 2:"))
print("sum:",a+b)
print("difference:",a-b)
print("product:",a*b)
print("quotient:",a/b)
print("remainder:",a%b)
print("power:",a**b)