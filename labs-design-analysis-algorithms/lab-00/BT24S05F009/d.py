# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
a = int(input("Enter first number"))
b = int(input("Enter second number"))
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(pow(a,b))
