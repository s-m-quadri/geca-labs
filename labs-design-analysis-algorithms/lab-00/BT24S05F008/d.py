# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)


a = int(input("Enter Number 1 : "))
b = int(input("Enter Number 2 : "))
print("sum : ",a+b)
print("Difference : ",a-b)
print("Product : ",a*b)
print("Quotient : ",a//b)
print("Remainder : ",a%b)
print("Power : ",a**b)
# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
