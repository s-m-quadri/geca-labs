# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()


words = []
words.append("zebra")
words.append("apple")
words.append("monkey")

words.sort()
print("Sorted:", words)

words.reverse()
print("Reversed:", words)