# ✅ TASK:
# Ask user for a sentence.
# Then:
#  - Print it in uppercase.
#  - Print it reversed.
#  - Print its length.

# 💡 TIP:
# Use `.upper()`, slicing `[::-1]`, and `len()`.
string = input("Enter a sentence: ")
print("Uppercase:", string.upper())
print("Reversed:", string[::-1])
print("Length:", len(string))


