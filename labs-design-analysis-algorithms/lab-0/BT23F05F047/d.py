# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
x=input("Enter first number")
y=input("Enter second number")
a=int(x)
b=int(y)
print("Sum is :",a+b)
print("Difference is :",a-b)
print("Product is :",a*b)
print("Quotient is :",a/b)
print("Remainder is :",a%b)
print("Power is :",a^b)
