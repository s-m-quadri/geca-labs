# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
a = int(input("first num:"))
b = int(input("second num:"))
c = a+b
d = a-b
m = a*b
s = a/b
r = a%b
p = a^b
print(c)
print(d)
print(m)
print(s)
print(r)
print(p)
