# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.

a = int(input("enter a"))
b = int(input("enter b"))
sum=a+b
diff=a-b
product=a*b
quotient=a/b
remainder=a%b
power=(a^b)
print(sum)
print(diff)
print(product)
print(quotient)
print(remainder)
print(power)
