# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.

x = int(input("Enter the first number: "))
y = int(input("Enter the second number: "))

print("sum:", x + y)
print("difference:", x - y)
print("product:", x * y)
print("quotient:", x / y)
print("remainder:", x % y)
print("power:", x ** y)
