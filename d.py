# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

a = int(input("Enter Number 1 : "))
b = int(input("Enter Number 2 : "))
print(a+b)
print(a-b)
print(a*b)
print(a//b)
print(a**b)
# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
