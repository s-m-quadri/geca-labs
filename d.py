# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.

n1 = int(input("Enter first number: "))
n2 = int(input("Enter second number: "))

print("Sum : ",n1+n2)
print("Difference : ",n1-n2)
print("Product : ",n1*n2)
print("Quotient : ",n1/n2)
print("remainder : ",n1%n2)
print("power : ",n1^n2)

