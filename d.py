# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))
print("Sum:",a+b)
print("Difference: ",a-b)
print("Product: ",a*b)
print("quotient: ",a/b)
print("remainder: ",a%b)
print("Power: ",a**b)
