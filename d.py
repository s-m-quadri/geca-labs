# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
num1 = input()
num2 = input()
print(int(num1)+int(num2))
print(int(num1)-int(num2))
print(int(num1)*int(num2))
print(int(num1)/int(num2))
print(int(num1)%int(num2))
print(int(num1)**int(num2))
