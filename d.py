# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.
num1=int(input("Enter number one:"))
num2=int(input("Enter number two:"))
sum=num1+num2
difference=num1-num2
product=num1*num2
quotient=num1/num2
remainder=num1%num2
power=num1^num2
print(sum)
print(difference)
print(product)
print(quotient)
print(remainder)
print(power)