# Hotel Booking Management System

## 1. Introduction

This project is a relational database system designed to manage hotel operations such as rooms, guests, bookings, and payments.

It demonstrates how multiple entities interact in a real-world booking system.

---

## 2. Objective

- Design structured tables with relationships
- Implement foreign key constraints
- Store realistic booking and payment data
- Write queries for business insights

---

## 3. Tables Used

1. Hotel      → Stores hotel details  
2. Room       → Stores rooms in each hotel  
3. Guest      → Stores customer details  
4. Booking    → Links guest and room  
5. Payment    → Stores payment details  

