# Write a program that takes two numbers from the user.
# Print their:
#  - sum
#  - difference
#  - product
#  - quotient
#  - remainder
#  - power (x^y)

# 💡 TIP:
# Use `+`, `-`, `*`, `/`, `%`, and `**`.

a = int(input("Enter 1st number"))
b = int(input("Enter 2nd number"))
print("Sum", a+b)
print("Difference", a-b)
print("Product", a*b)
print("Quotient", a/b)
print("Remainder", a%b)
print("Power", a**b)