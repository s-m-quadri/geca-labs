# Taking two numbers as input from the user
x = float(input("Enter first number: "))
y = float(input("Enter second number: "))

# Performing operations
print("Sum:", x + y)
print("Difference:", x - y)
print("Product:", x * y)
print("Quotient:", x / y)
print("Remainder:", x % y)
print("Power:", x ** y)
