# Ask the user to enter a number.
# Print:
#  - "Positive" if it's > 0
#  - "Negative" if it's < 0
#  - "Zero" if it's 0

# 💡 TIP:
# Use `if`, `elif`, and `else`.
# Asking the user for a number
num = int(input("Enter a number: "))

# Checking conditions
if num > 0:
    print("Positive")
elif num < 0:
    print("Negative")
else:
    print("Zero")

