# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()

# Create an empty list
my_list = []

# Append 3 strings
my_list.append("orange")
my_list.append("apple")
my_list.append("banana")

# Sort the list
my_list.sort()

# Reverse the list
my_list.reverse()

# Print the final list
print(my_list)
