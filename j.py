# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()
animal= []
animal.append("Zebra")
animal.append("Yak")
animal.append("Tiger")
print(animal)
animal.sort()
print("Sorted: ",animal)
animal.reverse()
print("Reverse: ",animal)
print(animal)