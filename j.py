# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()

list= []

list.append("Aurangabad")
list.append("Jalna")
list.append("Pune")

list.sort()
print("Sorted list : ",list)

list.reverse()
print("Reversed : ",list)