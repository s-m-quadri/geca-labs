# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()
# Creating an empty list
words = []

# Appending 3 strings
words.append("banana")
words.append("apple")
words.append("cherry")

# Sorting the list
words.sort()

# Reversing the list
words.reverse()

# Printing the final list
print("Sorted in reverse order:", words)
