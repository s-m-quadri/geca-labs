# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()

words = []
words.append("hi")
words.append("bye")
words.append("good bye")

words.sort()
print("Sort:", words)

words.reverse()
print("Reverse:", words)