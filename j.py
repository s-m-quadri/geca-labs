# Create an empty list.
# Append 3 strings to it.
# Sort the list and print it in reverse order.

# 💡 TIP:
# Use .append(), .sort(), and .reverse()

# Create an empty list
words = []

# Append 3 strings
words.append("banana")
words.append("apple")
words.append("cherry")

# Sort the list (alphabetical order)
words.sort()

# Reverse the list
words.reverse()

# Print the final list
print("Final list:", words)

