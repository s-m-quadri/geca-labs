# Import the `math` module and use it to calculate:
#  - The square root of 144
#  - The value of π
#  - sin(90 degrees) converted to radians

# 💡 TIP:
# Use `import math`, and remember degrees must be converted to radians.
import math
print(math.sqrt(144))
print(math.pi)
print(math.sin(math.radians(90)))
